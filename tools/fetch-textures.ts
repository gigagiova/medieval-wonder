// Downloads the CC0 photo-scanned PBR sets the world's materials use (Poly
// Haven) and packs them for the game:
//
//   npx tsx tools/fetch-textures.ts
//
// For each set it writes, into public/textures/:
//   <slot>_a.webp  albedo (sRGB)
//   <slot>_n.webp  normal map, OpenGL convention (+Y up)
//   <slot>_m.webp  R ambient occlusion, G roughness, B height (displacement)
// and records every source URL in public/textures/CREDITS.md.
//
// Downloads go through curl (it honours the environment's proxy) into
// tools/.cache/, so re-running only re-packs.

import sharp from 'sharp';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';

const OUT = new URL('../public/textures/', import.meta.url).pathname;
const CACHE = new URL('./.cache/', import.meta.url).pathname;

/** slot (what the shaders call it) → Poly Haven asset, resolution, and why. */
export const SETS: { slot: string; asset: string; res: '1k' | '2k'; use: string }[] = [
  { slot: 'cobble', asset: 'cobblestone_02', res: '2k', use: 'alleys: rounded river cobbles set close (acciottolato)' },
  { slot: 'basoli', asset: 'monastery_stone_floor', res: '2k', use: 'Roman basalt paving of the main lane; church slab floors' },
  { slot: 'mud', asset: 'forest_ground_04', res: '1k', use: 'yards, outside the walls: trodden earth with pebbles' },
  { slot: 'rubble', asset: 'plaster_stone_wall_02', res: '2k', use: 'house walls: river stones laid in lime mortar' },
  { slot: 'ashlar', asset: 'castle_wall_varriation', res: '2k', use: 'church, palace and gate masonry: coursed mixed stone' },
  { slot: 'bigstone', asset: 'broken_wall', res: '1k', use: 'ruinous limestone rubble' },
  { slot: 'brick', asset: 'red_bricks_02', res: '2k', use: 'Roman brick in thick, decayed mortar' },
  { slot: 'plaster', asset: 'plaster_stone_wall_01', res: '1k', use: 'lime plaster over stone, patched and holed' },
  { slot: 'tuff', asset: 'quarry_wall_02', res: '2k', use: 'catacombs: rock hewn with picks' },
  { slot: 'wood', asset: 'weathered_planks', res: '1k', use: 'doors, shutters, beams, galleries' },
  { slot: 'coppi', asset: 'roof_tiles_14', res: '1k', use: 'roofs: old curved clay tiles' },
  { slot: 'marble', asset: 'rock_boulder_dry', res: '1k', use: 'weathered marble / travertine spolia' },
  { slot: 'bark', asset: 'bark_willow', res: '1k', use: 'forest trees' },
  { slot: 'block', asset: 'rock_surface', res: '1k', use: 'single dressed stones: quoins, voussoirs, sills, plinth blocks' },
];

function curl(url: string, dest: string) {
  if (existsSync(dest)) return;
  execFileSync('curl', ['-sSfL', '--retry', '3', '-o', dest, url], { stdio: 'inherit' });
}

const files = (asset: string) => JSON.parse(execFileSync('curl', ['-sSf', `https://api.polyhaven.com/files/${asset}`]).toString());

mkdirSync(OUT, { recursive: true });
mkdirSync(CACHE, { recursive: true });
const credits: string[] = [
  '# Texture credits',
  '',
  'All photo-scanned texture sets are from [Poly Haven](https://polyhaven.com), released under',
  '[CC0](https://creativecommons.org/publicdomain/zero/1.0/) (no attribution required; credited here anyway).',
  '`noise.png` is generated by `tools/bake-textures.ts`.',
  '',
  '| in game | Poly Haven asset | used for | maps |',
  '|---|---|---|---|',
];

for (const s of SETS) {
  const f = files(s.asset);
  const pick = (k: string) => f[k][s.res].jpg.url as string;
  const src = { diff: pick('Diffuse'), nor: pick('nor_gl'), arm: pick('arm'), disp: pick('Displacement') };
  const local: Record<string, string> = {};
  for (const [k, url] of Object.entries(src)) {
    local[k] = `${CACHE}${s.asset}_${k}_${s.res}.jpg`;
    curl(url, local[k]);
  }
  const q = s.res === '2k' ? 80 : 84;
  await sharp(local.diff).webp({ quality: q, effort: 5 }).toFile(`${OUT}${s.slot}_a.webp`);
  await sharp(local.nor).webp({ quality: q + 6, effort: 5 }).toFile(`${OUT}${s.slot}_n.webp`);
  // Pack AO (arm.r), roughness (arm.g) and height (displacement) at 1k.
  const M = 1024;
  const arm = await sharp(local.arm).resize(M, M).removeAlpha().raw().toBuffer();
  const disp = await sharp(local.disp).resize(M, M).greyscale().raw().toBuffer();
  const pack = Buffer.alloc(M * M * 3);
  for (let i = 0; i < M * M; i++) {
    pack[i * 3] = arm[i * 3];
    pack[i * 3 + 1] = arm[i * 3 + 1];
    pack[i * 3 + 2] = disp[i];
  }
  await sharp(pack, { raw: { width: M, height: M, channels: 3 } }).webp({ quality: 88, effort: 5 }).toFile(`${OUT}${s.slot}_m.webp`);
  credits.push(`| \`${s.slot}\` | [${s.asset}](https://polyhaven.com/a/${s.asset}) (${s.res}) | ${s.use} | ${Object.values(src).map((u) => `[${u.split('/').pop()}](${u})`).join(', ')} |`);
  console.log(s.slot, '←', s.asset, s.res);
}
writeFileSync(`${OUT}CREDITS.md`, credits.join('\n') + '\n');
